const fs = require('fs');
const path = require('path');

const filePath = path.join(__dirname, '../src/astronomy/theories/vsop87/vsop87Coefficients.ts');
const fileContent = fs.readFileSync(filePath, 'utf-8');

// Regex to find all arrays
const arrayRegex = /const _([A-Z0-9]+) = new Float64Array\(\[([\s\S]*?)\]\);/g;

function encodeSeries(numbers) {
    const len = numbers.length / 3;
    const buffer = new ArrayBuffer(len * 3 * 8);
    const view = new Float64Array(buffer);
    for (let i = 0; i < len * 3; i++) {
        view[i] = numbers[i];
    }
    return Buffer.from(buffer).toString('base64');
}

let output = `// Auto-generated by scripts/pack-coefficients.js
// Do not edit manually.

export interface ParallelSeries {
  A: Float64Array;
  B: Float64Array;
  C: Float64Array;
}

/**
 * Instantly converts a Base64 string into a ParallelSeries of Float64Arrays.
 * Bypasses V8 AST array parsing, reducing TTI significantly.
 */
export function decodeBase64Series(base64: string): ParallelSeries {
  // Use atob if in browser, or Buffer in Node for compatibility
  const binaryString = typeof atob === 'function' ? atob(base64) : Buffer.from(base64, 'base64').toString('binary');
  const len = binaryString.length;
  const bytes = new Uint8Array(len);
  
  for (let i = 0; i < len; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  
  const interleaved = new Float64Array(bytes.buffer);
  const terms = interleaved.length / 3;
  
  const A = new Float64Array(terms);
  const B = new Float64Array(terms);
  const C = new Float64Array(terms);
  
  for (let i = 0; i < terms; i++) {
    A[i] = interleaved[i * 3];
    B[i] = interleaved[i * 3 + 1];
    C[i] = interleaved[i * 3 + 2];
  }
  
  return { A, B, C };
}

`;

let match;
while ((match = arrayRegex.exec(fileContent)) !== null) {
    const key = match[1];
    const arrayContent = match[2];
    
    // Parse the numbers
    const numbers = arrayContent
        .split(',')
        .map(n => n.trim())
        .filter(n => n.length > 0)
        .map(n => parseFloat(n));
        
    const base64 = encodeSeries(numbers);
    console.log(`Packed ${key}: ${numbers.length / 3} terms -> ${base64.length} chars (Base64)`);
    output += `export const ${key} = decodeBase64Series("${base64}");\n\n`;
}

const outPath = path.join(__dirname, '../src/astronomy/theories/vsop87/vsop87Packed.ts');
fs.writeFileSync(outPath, output);
console.log(`Successfully generated ${outPath}`);
