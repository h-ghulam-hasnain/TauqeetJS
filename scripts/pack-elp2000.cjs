const fs = require('fs');
const path = require('path');

const content = fs.readFileSync('./src/astronomy/theories/elp2000/elp2000Data.ts', 'utf-8');
const lines = content.split('\n').filter(line => !line.startsWith('//'));
const jsonStr = lines.join('').replace('export const elp2000Data = ', '').trim().replace(/;$/, '');
const elpData = JSON.parse(jsonStr);

function packArray(arr, keys) {
    const buffer = new ArrayBuffer(arr.length * keys.length * 8);
    const view = new Float64Array(buffer);
    let i = 0;
    for (const item of arr) {
        for (const key of keys) {
            // Some objects might be missing B, default to 0
            view[i++] = item[key] !== undefined ? item[key] : 0;
        }
    }
    return Buffer.from(buffer).toString('base64');
}

