for (const key of Object.keys(elpData)) {
    if (key === 'truncationArcSeconds' || key === 'truncationKilometers') {
        output += `elp2000Data['${key}'] = ${elpData[key]};\n`;
        continue;
    }
    
    let keys;
    let typeName;
    if (key.match(/ELP0[123]/)) {
        keys = keysMain;
        typeName = 'keysMain';
    } else if (key.match(/ELP(0[4-9]|2[2-9]|3[0-6])/)) {
        keys = keysNonPlanetary;
        typeName = 'keysNonPlanetary';
    } else {
        keys = keysPlanetary;
        typeName = 'keysPlanetary';
    }

    const base64 = packArray(elpData[key], keys);
    console.log(`Packed ${key}: ${elpData[key].length} terms -> ${base64.length} chars`);
    
    output += `elp2000Data['${key}'] = createProxy("${base64}", ${typeName});\n`;
}

const outPath = path.join(__dirname, '../src/astronomy/theories/elp2000/elp2000Packed.ts');
fs.writeFileSync(outPath, output);
console.log(`Successfully generated ${outPath}`);
